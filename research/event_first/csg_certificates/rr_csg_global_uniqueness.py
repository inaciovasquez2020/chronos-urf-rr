def trim(a):
 while len(a)>1 and a[-1]==0:a.pop()
 return a
def deriv(a):return trim([a[i]*i for i in range(1,len(a))])
def rem(a,b):
 a=a[:]
 while len(a)>=len(b) and any(a):
  n=len(a)-len(b);c=a[-1]/b[-1]
  for j in range(len(b)):a[n+j]-=c*b[j]
  trim(a)
 return a
def sturm(p):
 out=[p,deriv(p)]
 while len(out[-1])>1:
  v=[-q for q in rem(out[-2],out[-1])]
  assert any(v)
  # positive scaling to bound intermediate numbers
  nums=[abs(q.numerator) for q in v if q]
  dens=[q.denominator for q in v]
  from math import gcd,lcm
  dd=1
  for d in dens:dd=lcm(dd,d)
  ints=[int(q*dd) for q in v]
  gg=0
  for k in ints:gg=gcd(gg,k)
  v=[F(k,gg) for k in ints]
  out.append(v)
 return out
def evalp(p,t):
 s=F(0)
 for v in reversed(p):s=s*t+v
 return s
def changes(seq,t):
 signs=[]
 for p in seq:
  q=evalp(p,t)
  if q:signs.append(1 if q>0 else -1)
 return sum(a!=b for a,b in zip(signs,signs[1:]))
